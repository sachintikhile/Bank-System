import { store } from '../store.js';

/**
 * Authentication and Step-Up MFA Modal Component
 */
export class AuthModalComponent {
  constructor() {
    this.isOpen = false;
    this.step = 'LOGIN'; // 'LOGIN' | 'MFA' | 'LOGGED_IN'
    this.initDOM();
  }

  initDOM() {
    let overlay = document.getElementById('auth-modal-overlay');
    if (!overlay) {
      overlay = document.createElement('div');
      overlay.id = 'auth-modal-overlay';
      overlay.className = 'modal-overlay';
      document.body.appendChild(overlay);
    }
    this.overlay = overlay;
    this.render();
  }

  open(step = 'LOGIN') {
    this.step = step;
    this.isOpen = true;
    this.overlay.classList.add('active');
    this.render();
  }

  close() {
    this.isOpen = false;
    this.overlay.classList.remove('active');
  }

  render() {
    if (!this.overlay) return;

    if (this.step === 'LOGIN') {
      this.overlay.innerHTML = `
        <div class="auth-card">
          <div class="auth-header">
            <div class="brand-icon" style="margin: 0 auto; width: 44px; height: 44px;">A</div>
            <h2>Sign In to ApexBank</h2>
            <p>Access your institutional digital core account</p>
          </div>
          <form id="login-form">
            <div class="form-group">
              <label class="form-label">Client Identifier / Email</label>
              <input type="text" id="auth-email" class="form-input" value="sachin@apexbank.io" required />
            </div>
            <div class="form-group">
              <label class="form-label">Security Password</label>
              <input type="password" id="auth-password" class="form-input" value="••••••••••••" required />
            </div>
            <button type="submit" class="btn btn-primary" style="width: 100%; padding: 12px; margin-top: 8px;">
              Authenticate Session
            </button>
            <button type="button" id="auth-cancel" class="btn btn-secondary" style="width: 100%; margin-top: 10px;">
              Cancel
            </button>
          </form>
        </div>
      `;

      this.overlay.querySelector('#login-form').addEventListener('submit', (e) => {
        e.preventDefault();
        this.step = 'MFA';
        this.render();
      });

      this.overlay.querySelector('#auth-cancel').addEventListener('click', () => this.close());
    } else if (this.step === 'MFA') {
      this.overlay.innerHTML = `
        <div class="auth-card">
          <div class="auth-header">
            <div class="brand-icon" style="margin: 0 auto; width: 44px; height: 44px; background: #10B981;">🛡️</div>
            <h2>Step-Up MFA Required</h2>
            <p>Enter the 6-digit TOTP token generated by your authenticator app</p>
          </div>
          <form id="mfa-form">
            <div class="mfa-digits-container">
              <input type="text" class="mfa-digit" maxlength="1" value="7" />
              <input type="text" class="mfa-digit" maxlength="1" value="2" />
              <input type="text" class="mfa-digit" maxlength="1" value="9" />
              <input type="text" class="mfa-digit" maxlength="1" value="4" />
              <input type="text" class="mfa-digit" maxlength="1" value="1" />
              <input type="text" class="mfa-digit" maxlength="1" value="8" />
            </div>
            <button type="submit" class="btn btn-primary" style="width: 100%; padding: 12px;">
              Confirm Authorization
            </button>
            <button type="button" id="mfa-back" class="btn btn-secondary" style="width: 100%; margin-top: 10px;">
              Back
            </button>
          </form>
        </div>
      `;

      this.overlay.querySelector('#mfa-form').addEventListener('submit', (e) => {
        e.preventDefault();
        store.setState({
          notifications: [
            { id: Date.now(), text: 'Multi-factor authentication confirmed. Session verified.', read: false },
            ...store.getState().notifications,
          ],
        });
        this.close();
      });

      this.overlay.querySelector('#mfa-back').addEventListener('click', () => {
        this.step = 'LOGIN';
        this.render();
      });
    }
  }
}

export const authModal = new AuthModalComponent();
